# ---------------------------------------------------------------------------
# THREAD INDEX HELPERS (so the sidebar / history survive a page refresh)
# ---------------------------------------------------------------------------
def _read_threads():
    if not os.path.exists(THREADS_INDEX_PATH):
        return []
    try:
        with open(THREADS_INDEX_PATH, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return []


def _write_threads(threads):
    with open(THREADS_INDEX_PATH, "w", encoding="utf-8") as f:
        json.dump(threads, f, ensure_ascii=False, indent=2)


def _ui_history_path(thread_id: str) -> str:
    # UUIDs are generated by this app; replacing path separators is an extra
    # guard because this value is also received from the browser.
    safe_id = str(thread_id).replace("/", "_").replace("\\\\", "_")
    return os.path.join(UI_HISTORY_DIR, f"{safe_id}.json")


def _read_ui_history(thread_id: str) -> list:
    path = _ui_history_path(thread_id)
    if not os.path.exists(path):
        return []
    try:
        with open(path, "r", encoding="utf-8") as f:
            value = json.load(f)
        return value if isinstance(value, list) else []
    except Exception:
        logger.warning("Could not read UI history for %s", thread_id)
        return []


def _write_ui_history(thread_id: str, turns: list):
    path = _ui_history_path(thread_id)
    temp_path = f"{path}.tmp"
    with open(temp_path, "w", encoding="utf-8") as f:
        json.dump(turns[-80:], f, ensure_ascii=False, indent=2)
    os.replace(temp_path, path)


def _append_ui_turn(thread_id: str, turn: dict):
    turns = _read_ui_history(thread_id)
    turns.append(turn)
    _write_ui_history(thread_id, turns)


def _replace_last_assistant_turn(thread_id: str, turn: dict):
    turns = _read_ui_history(thread_id)
    for index in range(len(turns) - 1, -1, -1):
        if turns[index].get("role") == "assistant":
            turns[index] = turn
            _write_ui_history(thread_id, turns)
            return
    turns.append(turn)
    _write_ui_history(thread_id, turns)


async def _touch_thread(thread_id: str, title: str | None = None):
    async with _threads_lock:
        threads = _read_threads()
        now = datetime.now(timezone.utc).isoformat()
        found = None
        for t in threads:
            if t["id"] == thread_id:
                found = t
                break
        if found is None:
            found = {
                "id": thread_id,
                "title": title or "নতুন কথোপকথন",
                "created_at": now,
                "updated_at": now,
            }
            threads.insert(0, found)
        else:
            found["updated_at"] = now
            if title and found.get("title") == "নতুন কথোপকথন":
                found["title"] = title
            threads.remove(found)
            threads.insert(0, found)
        _write_threads(threads)


